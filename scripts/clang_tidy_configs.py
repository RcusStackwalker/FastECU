#!/usr/bin/env python3
"""Generate the clang-tidy configuration chains the Bazel lint aspect reads.

Each directory holding a `.clang-tidy` maps to that file plus its parents, for as long as
each file says `InheritParentConfig: true`. The aspect keeps only a source's chain as action
inputs, so editing one config re-runs only the translation units it governs. Starlark cannot
read file contents, so this script reads them and writes `bazel/clang_tidy_config_chains.bzl`;
it also makes sure every config's package exports the file.

Exit codes: 0 = unchanged, 1 = files were (or, with --check, would be) changed, 2 = a config
is not in a Bazel package.
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from collections.abc import Callable, Sequence
from pathlib import Path, PurePosixPath
from typing import TextIO

import yaml

CONFIG_NAME = ".clang-tidy"
OUTPUT = "bazel/clang_tidy_config_chains.bzl"
BUILD_NAME = "BUILD.bazel"
ListConfigs = Callable[[Path], Sequence[str]]

_EXPORTS = re.compile(r'exports_files\(\s*\[[^\]]*"\.clang-tidy"')
_EXPORT_LINE = f'exports_files(["{CONFIG_NAME}"])\n'


def git_list_configs(root: Path) -> list[str]:
    """Tracked and untracked (not ignored) configuration files, repo-relative."""
    listing = subprocess.run(
        [
            "git",
            "ls-files",
            "--cached",
            "--others",
            "--exclude-standard",
            "--",
            CONFIG_NAME,
            f"*/{CONFIG_NAME}",
        ],
        cwd=root,
        check=True,
        capture_output=True,
        text=True,
    )
    return sorted({line for line in listing.stdout.splitlines() if line})


def inherits_parent(text: str) -> bool:
    loaded = yaml.safe_load(text)
    return isinstance(loaded, dict) and loaded.get("InheritParentConfig") is True


def _directory(config: str) -> str:
    parent = PurePosixPath(config).parent.as_posix()
    return "" if parent == "." else parent


def _config_path(directory: str) -> str:
    return f"{directory}/{CONFIG_NAME}" if directory else CONFIG_NAME


def _parent_directories(directory: str) -> list[str]:
    parts = directory.split("/") if directory else []
    return ["/".join(parts[:count]) for count in range(len(parts) - 1, -1, -1)]


def compute_chains(root: Path, configs: Sequence[str]) -> dict[str, list[str]]:
    directories = {_directory(config) for config in configs}
    chains: dict[str, list[str]] = {}
    for directory in sorted(directories):
        chain = [_config_path(directory)]
        current = directory
        while inherits_parent((root / _config_path(current)).read_text(encoding="utf-8")):
            parent = next((p for p in _parent_directories(current) if p in directories), None)
            if parent is None:
                break
            chain.append(_config_path(parent))
            current = parent
        chains[directory] = chain
    return chains


def render_bzl(chains: dict[str, list[str]]) -> str:
    lines = [
        '"""Generated by scripts/clang_tidy_configs.py; do not edit."""',
        "",
        "# Directory holding a .clang-tidy -> that file plus the parents it inherits from.",
        "CONFIG_CHAINS = {",
    ]
    for directory in sorted(chains):
        files = ", ".join(f'"{path}"' for path in chains[directory])
        lines.append(f'    "{directory}": [{files}],')
    lines += ["}", "", "CONFIG_LABELS = ["]
    lines += [f'    "//{directory}:{CONFIG_NAME}",' for directory in sorted(chains)]
    lines += ["]", ""]
    return "\n".join(lines)


def add_export(build_text: str) -> str | None:
    """The BUILD file with the config exported, or None when it already is."""
    if _EXPORTS.search(build_text):
        return None
    separator = "" if not build_text or build_text.endswith("\n\n") else "\n"
    if build_text and not build_text.endswith("\n"):
        separator = "\n\n"
    return build_text + separator + _EXPORT_LINE


def run(
    root: Path,
    *,
    check: bool,
    list_configs: ListConfigs = git_list_configs,
    err: TextIO = sys.stderr,
) -> int:
    configs = list_configs(root)
    chains = compute_chains(root, configs)
    changes: dict[Path, str] = {}

    missing = [d for d in chains if not (root / d / BUILD_NAME).is_file()]
    if missing:
        for directory in missing:
            err.write(
                f"{_config_path(directory)}: {directory or '.'} has no {BUILD_NAME}; "
                "the aspect can only read a config that a Bazel package exports.\n"
            )
        return 2

    output = root / OUTPUT
    rendered = render_bzl(chains)
    if not output.is_file() or output.read_text(encoding="utf-8") != rendered:
        changes[output] = rendered
    for directory in chains:
        build = root / directory / BUILD_NAME
        edited = add_export(build.read_text(encoding="utf-8"))
        if edited is not None:
            changes[build] = edited

    if not changes:
        return 0
    for path, text in changes.items():
        relative = path.relative_to(root).as_posix()
        if check:
            err.write(f"{relative} is out of date; run scripts/clang_tidy_configs.py\n")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
            err.write(f"updated {relative}\n")
    return 1


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="report drift instead of fixing it")
    args = parser.parse_args(argv)
    root = Path(
        subprocess.run(
            ["git", "rev-parse", "--show-toplevel"], check=True, capture_output=True, text=True
        ).stdout.strip()
    )
    return run(root, check=args.check)


if __name__ == "__main__":
    sys.exit(main())
